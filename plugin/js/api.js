/**
 * login(serverUrl, username, password, cb)
 * POST /api/auth/login  →  { token: "...", userId: "..." }
 *
 * @param {string}   serverUrl - Base URL of the MuseCollab server.
 * @param {string}   username  - Account username.
 * @param {string}   password  - Account password.
 * @param {Function} cb        - cb(error, { token, userId })
 */
function login(serverUrl, username, password, cb) {
    var url = serverUrl.replace(/\/$/, "") + "/api/auth/login";
    var body = JSON.stringify({ username: username, password: password });
    makeRequest("POST", url, { "Content-Type": "application/json" }, body, cb);
}

/**
 * register(serverUrl, username, password, cb)
 * POST /api/auth/register  →  { token, userId }
 *
 * Creates a new user account on the server. On success the caller receives
 * a session token that can be used immediately — no separate login required.
 *
 * @param {string}   serverUrl - Base URL of the MuseCollab server.
 * @param {string}   username  - Desired username (must be unique on the server).
 * @param {string}   password  - Desired password.
 * @param {Function} cb        - cb(error, { token, userId })
 */
function register(serverUrl, username, password, cb) {
    var url = serverUrl.replace(/\/$/, "") + "/api/auth/register";
    var body = JSON.stringify({ username: username, password: password });
    makeRequest("POST", url, { "Content-Type": "application/json" }, body, cb);
}

/**
 * joinProject(serverUrl, token, inviteCode, displayName, cb)
 * POST /api/auth/join  body { inviteCode, displayName }
 *
 * Adds the authenticated user as a collaborator on the project identified by
 * the invite code. The invite code is generated by the project owner via
 * createProject() and can be shared out-of-band.
 *
 * @param {string}   serverUrl   - Base URL of the MuseCollab server.
 * @param {string}   token       - Bearer token from login() or register().
 * @param {string}   inviteCode  - Invite code string shared by the project owner.
 * @param {string}   displayName - Friendly name e.g. "Rahul", "Alice".
 * @param {Function} cb          - cb(error, { projectId, name, displayName, branch })
 */
function joinProject(serverUrl, token, inviteCode, displayName, cb) {
    if (typeof displayName === "function") {
        cb = displayName;
        displayName = "";
    }
    var url = serverUrl.replace(/\/$/, "") + "/api/auth/join";
    var bodyObj = { inviteCode: inviteCode };
    if (displayName) bodyObj.displayName = displayName;
    var body = JSON.stringify(bodyObj);
    var headers = { "Content-Type": "application/json", "Authorization": "Bearer " + token };
    makeRequest("POST", url, headers, body, cb);
}

