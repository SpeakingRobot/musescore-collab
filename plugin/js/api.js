/**
 * api.js — MuseCollab network layer
 * All HTTP calls use XMLHttpRequest so this module works inside Qt/QML's
 * JavaScript engine (no fetch, no Node built-ins).
 *
 * Every public function follows the Node-style callback convention:
 *   cb(error, data)
 * where `error` is null on success or a string message on failure,
 * and `data` is the parsed JSON response body (or null on error).
 */

"use strict";

