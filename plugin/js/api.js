/**
 * makeRequest(method, url, headers, body, cb)
 *
 * @param {string}      method   - "GET", "POST", "PUT", "DELETE", etc.
 * @param {string}      url      - Fully-qualified URL.
 * @param {Object}      headers  - Key/value pairs added to the request.
 * @param {string|null} body     - Request body string, or null.
 * @param {Function}    cb       - cb(error, parsedData)
 */
function makeRequest(method, url, headers, body, cb) {
    var xhr = new XMLHttpRequest();
    xhr.open(method, url, true /* async */);

    // Apply caller-supplied headers
    if (headers && typeof headers === "object") {
        var keys = Object.keys(headers);
        for (var i = 0; i < keys.length; i++) {
            xhr.setRequestHeader(keys[i], headers[keys[i]]);
        }
    }

    xhr.onreadystatechange = function () {
        if (xhr.readyState !== XMLHttpRequest.DONE) {
            return;
        }

        var status = xhr.status;
        var responseText = xhr.responseText || "";
        var parsed = null;

        // Always attempt JSON parse; fall back gracefully
        if (responseText.length > 0) {
            try {
                parsed = JSON.parse(responseText);
            } catch (e) {
                // Non-JSON body — wrap it so callers can still read it
                parsed = { raw: responseText };
            }
        }

        if (status === 0) {
            // Network-level failure (no response at all)
            cb("Network error: could not reach server at " + url, null);
            return;
        }

        if (status >= 200 && status < 300) {
            cb(null, parsed);
        } else {
            // Extract a human-readable message from the body if possible
            var serverMsg = (parsed && (parsed.message || parsed.error || parsed.detail))
                            || ("HTTP " + status);
            cb(serverMsg, null);
        }
    };

    xhr.onerror = function () {
        cb("XMLHttpRequest error for " + url, null);
    };

    xhr.ontimeout = function () {
        cb("Request timed out for " + url, null);
    };

    xhr.timeout = 30000; // 30 s

    if (body !== null && body !== undefined) {
        xhr.send(body);
    } else {
        xhr.send();
    }
}

